export function trOnsite(text: string): string {
  return readLocale() === 'en' ? english[text] || text : text;
}

/** Traduce un código de rechazo o error del backend a un mensaje para el operador. */
export function onsiteReason(code: string | undefined): string {
  if (!code) return trOnsite('No se pudo completar la acción');
  const entry = reasons[code];
  if (!entry) return `${trOnsite('No se pudo completar la acción')} (${code})`;
  return readLocale() === 'en' ? entry[1] : entry[0];
}
